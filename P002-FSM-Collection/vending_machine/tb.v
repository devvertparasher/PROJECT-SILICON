`timescale 1ns/1ps

module tb;

    reg clk;
    reg rst;

    reg coin_5;
    reg coin_10;

    wire dispense;
    wire [1:0] change;


    //========================================================
    // DUT
    //========================================================

    vending_machine dut (
        .clk(clk),
        .rst(rst),

        .coin_5(coin_5),
        .coin_10(coin_10),

        .dispense(dispense),
        .change(change)
    );


    //========================================================
    // Clock
    //========================================================

    always #5 clk = ~clk;


    //========================================================
    // Waveform
    //========================================================

    initial begin
        $dumpfile("vending_machine.vcd");
        $dumpvars(0, tb);
    end


    //========================================================
    // Test Sequence
    //========================================================

    initial begin

        clk     = 0;
        rst     = 1;
        coin_5  = 0;
        coin_10 = 0;

        // Reset
        #20;
        rst = 0;


        //====================================================
        // TEST 1
        // ₹5 + ₹5 = ₹10
        // Should NOT dispense
        //====================================================

        #5;
        coin_5 = 1;

        #10;
        coin_5 = 0;

        #10;
        coin_5 = 1;

        #10;
        coin_5 = 0;

        #20;


        //====================================================
        // TEST 2
        // ₹5 + ₹10 = ₹15
        // Dispense + ₹0 change
        //====================================================

        #5;
        coin_5 = 1;

        #10;
        coin_5 = 0;

        #10;
        coin_10 = 1;

        #10;
        coin_10 = 0;

        #20;


        //====================================================
        // TEST 3
        // ₹10 + ₹5 = ₹15
        // Dispense + ₹0 change
        //====================================================

        #5;
        coin_10 = 1;

        #10;
        coin_10 = 0;

        #10;
        coin_5 = 1;

        #10;
        coin_5 = 0;

        #20;


        //====================================================
        // TEST 4
        // ₹10 + ₹10 = ₹20
        // Dispense + ₹5 change
        //====================================================

        #5;
        coin_10 = 1;

        #10;
        coin_10 = 0;

        #10;
        coin_10 = 1;

        #10;
        coin_10 = 0;

        #20;


        //====================================================
        // TEST 5
        // No coin
        // Machine stays IDLE
        //====================================================

        #30;


        //====================================================
        // TEST 6
        // Both coins simultaneously
        // Invalid → ignored
        //====================================================

        #5;
        coin_5  = 1;
        coin_10 = 1;

        #10;
        coin_5  = 0;
        coin_10 = 0;

        #20;


        $finish;

    end


    //========================================================
    // Monitor
    //========================================================

    initial begin

        $monitor(
            "Time=%0t | rst=%b | coin5=%b | coin10=%b | state=%b | dispense=%b | change=%b",
            $time,
            rst,
            coin_5,
            coin_10,
            dut.current_state,
            dispense,
            change
        );

    end

endmodule
